class BudgetTracker:
    def __init__(self, max_calls: int, min_interval_s: float):
        self.max_calls = max_calls
        self.min_interval_s = min_interval_s
        self.attempts = 0
        self.last_attempt_time: float | None = None

    def on_attempt(self) -> None:
        if self.attempts >= self.max_calls:
            raise BudgetExhausted(f"Attempt budget exceeded: {self.attempts}/{self.max_calls}")
        now = time.monotonic()
        if self.last_attempt_time is not None:
            elapsed = now - self.last_attempt_time
            if elapsed < self.min_interval_s:
                time.sleep(self.min_interval_s - elapsed)
        self.last_attempt_time = time.monotonic()
        self.attempts += 1


def write_atomic_file(target_path: Path, data: str) -> None:
    target_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = target_path.with_suffix(target_path.suffix + ".tmp")
    tmp_path.write_text(data, encoding="utf-8")
    os.replace(tmp_path, target_path)


def format_markdown_review(nb_id: str, batch_reports: list[dict[str, Any]]) -> str:
    lines = [f"# Question Bank Review: {nb_id}\n"]
    for rep in batch_reports:
        tid = rep["topic_id"]
        qtype = rep["type"]
        qids = rep.get("qids", [])
        gen = rep.get("generator_model")
        checker = rep.get("checker_model")
        model_info = ""
        if gen:
            model_info = f" - generated by {gen}"
            if qtype == "mcq" and checker:
                model_info += f", checked by {checker}"
        lines.append(f"## Topic {tid} - {qtype.upper()} ({len(qids)} questions){model_info}\n")

        questions = get_questions(nb_id, qids)
        for qid in sorted(qids):
            q = questions.get(qid)
            if not q:
                lines.append(f"### {qid} (Missing document)\n")
                continue

            lines.append(f"### {qid} [{q.status.upper()}] (Difficulty {q.difficulty})\n")
            lines.append(f"**Stem**: {q.stem}\n")

            if q.type == "mcq":
                lines.append("**Options**:")
                for opt in q.options:
                    misc = f" *(Misconception: {opt.misconception})*" if opt.misconception else ""
                    lines.append(f"- **{opt.id}**: {opt.text}{misc}")
                lines.append(f"\n**Answer Key**: {q.answer.option_id}\n")
            else:
                lines.append(f"**Answer Value**: {q.answer.value}\n")
                if q.solution_code:
                    lines.append(f"**Solution Code**:\n```python\n{q.solution_code}\n```\n")

            lines.append(f"**Explanation**: {q.explanation}\n")
            verdict_str = 'PASSED' if q.verification.passed else 'FAILED'
            lines.append(
                f"**Verification**: {q.verification.method} ({verdict_str}) - "
                f"{q.verification.detail}\n"
            )

            cit_labels = [c.label for c in q.citations]
            lines.append(f"**Citations**: {', '.join(cit_labels) if cit_labels else 'None'}\n")
            lines.append("---\n")
    return "\n".join(lines)


def finalize(
    notebook_id: str,
    batch_reports: list[dict[str, Any]],
    budget: BudgetTracker,
    max_calls: int,
    status: str,
) -> None:
    counts_items = bank_counts(notebook_id)
    total_verified = sum(item.verified for item in counts_items)
    set_questions_verified(notebook_id, total_verified)

    course_dir_val = os.environ.get("COURSE_DATA_DIR")
    if course_dir_val:
        out_dir = Path(course_dir_val) / "derived" / "question_bank"
        report_data = {
            "notebook_id": notebook_id,
            "status": status,
            "total_verified": total_verified,
            "attempts_used": budget.attempts,
            "batches": batch_reports,
        }
        write_atomic_file(out_dir / "report.json", json.dumps(report_data, indent=2))
        md_content = format_markdown_review(notebook_id, batch_reports)
        write_atomic_file(out_dir / "questions.md", md_content)
        print(f"Derived reports written to {out_dir}")

    print(
        f"\nQuestion bank completed ({status}) for {notebook_id}: "
        f"total_verified={total_verified}, attempts_used={budget.attempts}/{max_calls}."
    )


def build_question_bank(
    notebook_id: str,
    topics: list[str],
    types: list[str],
    per_type: int,
    max_calls: int,
    min_interval_s: float,
    dry_run: bool = False,
) -> int:
    verify_emulator_preconditions()

    settings = get_settings()
    chain = settings.gemini_model_chain
    if "mcq" in types and len(chain) < 2:
        logger.error(
            "Safety violation: fewer than 2 models in chain for mcq blind check (%r)", chain
        )
        return 2

    # Verify target notebook exists
    nb_snap = get_notebook_snapshot(notebook_id)
    if not nb_snap.exists:
        logger.error("Notebook %s not found", notebook_id)
        return 2

    budget = BudgetTracker(max_calls=max_calls, min_interval_s=min_interval_s)

    if dry_run:
        print(f"=== DRY RUN: Question Bank Build for {notebook_id} ===")
        total_planned_calls = 0
        for tid in topics:
            for qtype in types:
                passages = select_topic_passages(notebook_id, tid, qtype)
                calls_for_batch = 2 if qtype == "mcq" else 2  # gen + blind/retry
                total_planned_calls += calls_for_batch
                total_tokens = sum(p.token_count for p in passages)
                print(
                    f"\nTopic {tid} ({qtype}): {len(passages)} passages chosen "
                    f"({total_tokens} tokens), {calls_for_batch} planned calls"
                )
                for p in passages:
                    loc_label = format_passage_location(p)
                    print(
                        f"  - [{p.passage_num}] {p.chunk_id} "
                        f"({p.title}, {loc_label}, {p.token_count} tokens)"
                    )
        print(f"\nTotal planned calls across {len(topics)} topics: {total_planned_calls}")
        return 0

    batch_reports: list[dict[str, Any]] = []
    had_model_error = False

    print(
        f"Building question bank for {notebook_id} "
        f"(topics={topics}, types={types}, per_type={per_type})..."
    )

    for tid in topics:
        topic_snap = get_topic_snapshot(notebook_id, tid)
        t_data = topic_snap.to_dict() or {} if topic_snap.exists else {}
        t_name = t_data.get("name", tid)
        t_summary = t_data.get("summary", "")

        for qtype in types:
            passages = select_topic_passages(notebook_id, tid, qtype)
            if not passages:
                logger.warning("No passages found for topic %s, skipping", tid)
                continue

            try:
                if qtype == "mcq":
                    stored_pairs, report = process_mcq_batch(
                        nb_id=notebook_id,
                        topic_id=tid,
                        topic_name=t_name,
                        topic_summary=t_summary,
                        passages=passages,
                        count=per_type,
                        configured_chain=chain,
                        on_attempt=budget.on_attempt,
                    )
                else:
                    stored_pairs, report = process_numerical_batch(
                        nb_id=notebook_id,
                        topic_id=tid,
                        topic_name=t_name,
                        topic_summary=t_summary,
                        passages=passages,
                        count=per_type,
                        configured_chain=chain,
                        on_attempt=budget.on_attempt,
                    )

                # Write each question document one by one with Q2 put_question
                batch_qids = []
                for qid, q_doc in stored_pairs:
                    put_question(notebook_id, qid, q_doc)
                    batch_qids.append(qid)

                # Scoped delete of stale questions for this topic and type
                deleted_stale = delete_stale_questions(notebook_id, tid, qtype, set(batch_qids))
                report["deleted_stale"] = deleted_stale
                report["qids"] = batch_qids
                batch_reports.append(report)

                print(
                    f"  [{tid}-{qtype}] generated={report['generated']}, "
                    f"verified={report['verified']}, rejected={report['rejected']}"
                )

            except BudgetExhausted as exc:
                print(f"\n[ABORTED] {exc}")
                print(f"Total attempts used: {budget.attempts}/{max_calls}")
                batch_reports.append({
                    "topic_id": tid,
                    "type": qtype,
                    "error": f"BudgetExhausted: {exc}",
                })
                finalize(
                    notebook_id=notebook_id,
                    batch_reports=batch_reports,
                    budget=budget,
                    max_calls=max_calls,
                    status="budget_exhausted",
                )
                return 3
            except QuotaExhausted as exc:
                print(f"\n[QUOTA EXHAUSTED] {exc}. Stopping run.")
                batch_reports.append({
                    "topic_id": tid,
                    "type": qtype,
                    "error": f"QuotaExhausted: {exc}",
                })
                finalize(
                    notebook_id=notebook_id,
                    batch_reports=batch_reports,
                    budget=budget,
                    max_calls=max_calls,
                    status="quota_exhausted",
                )
                return 1
            except errors.ClientError as exc:
                print(f"\n[REQUEST REJECTED] {exc.__class__.__name__}: {exc}")
                batch_reports.append({
                    "topic_id": tid,
                    "type": qtype,
                    "error": f"{exc.__class__.__name__}: {exc}",
                })
                finalize(
                    notebook_id=notebook_id,
                    batch_reports=batch_reports,
                    budget=budget,
                    max_calls=max_calls,
                    status="request_rejected",
                )
                return 1
            except (ModelUnavailable, UnreadableOutput) as exc:
                logger.error("Batch %s-%s failed with %s: skipping batch", tid, qtype, exc)
                had_model_error = True
                batch_reports.append({
                    "topic_id": tid,
                    "type": qtype,
                    "error": f"{exc.__class__.__name__}: {exc}",
                })
                continue

    status = "batches_failed" if had_model_error else "completed"
    finalize(
        notebook_id=notebook_id,
        batch_reports=batch_reports,
        budget=budget,
        max_calls=max_calls,
        status=status,
    )
    return 1 if had_model_error else 0


def main() -> None:
    parser = argparse.ArgumentParser(description="Build verified question bank for course.")
    parser.add_argument("--notebook", default=DEMO_NOTEBOOK_ID, help="Target notebook ID")
    parser.add_argument(
        "--topics", default="t1,t2,t3,t4,t5,t6", help="Comma-separated topics"
    )
    parser.add_argument(
        "--types", default="mcq,numerical", help="Comma-separated question types"
    )
    parser.add_argument(
        "--per-type", type=int, default=8, help="Number of questions per type (1..8)"
    )
    parser.add_argument(
        "--max-calls", type=int, default=40, help="Max real HTTP calls allowed"
    )
    parser.add_argument(
        "--min-interval-s", type=float, default=13.0, help="Min interval in seconds between calls"
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="Print planned passages and calls without writing"
    )
    args = parser.parse_args()

    topics_list = [t.strip() for t in args.topics.split(",") if t.strip()]
    types_list = [t.strip() for t in args.types.split(",") if t.strip()]

    code = build_question_bank(
        notebook_id=args.notebook,
        topics=topics_list,
        types=types_list,
        per_type=args.per_type,
        max_calls=args.max_calls,
        min_interval_s=args.min_interval_s,
        dry_run=args.dry_run,
    )
    sys.exit(code)


if __name__ == "__main__":
    main()
